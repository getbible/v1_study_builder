def write_bible_tree(root: Path, translations: dict[str, dict[str, Any]] | None = None) -> Path:
    """Write an API v2 tree under ``root`` and return it."""
    root.mkdir(parents=True, exist_ok=True)
    translations = translations if translations is not None else TRANSLATIONS
    catalogue: dict[str, Any] = {}
    for abbreviation, spec in translations.items():
        language = spec["lang"]
        document = {
            "translation": spec.get("title", abbreviation.upper()),
            "abbreviation": abbreviation,
            "description": spec.get("title", abbreviation.upper()),
            "lang": language,
            "language": spec.get("language", language),
            "direction": "LTR",
            "encoding": "UTF-8",
            "books": [],
        }
        index: dict[str, Any] = {}
        for number in sorted(spec["books"]):
            name, counts = spec["books"][number]
            chapters = []
            chapter_index: dict[str, Any] = {}
            for chapter, count in enumerate(counts, start=1):
                chapters.append(
                    {
                        "chapter": chapter,
                        "name": f"{name} {chapter}",
                        "verses": [
                            {
                                "chapter": chapter,
                                "verse": verse,
                                "name": f"{name} {chapter}:{verse}",
                                "text": "",
                            }
                            for verse in range(1, count + 1)
                        ],
                    }
                )
                chapter_index[str(chapter)] = {
                    "translation": document["translation"],
                    "abbreviation": abbreviation,
                    "lang": language,
                    "book_nr": number,
                    "book_name": name,
                    "chapter": chapter,
                    "name": f"{name} {chapter}",
                    "url": f"https://api.getbible.net/v2/{abbreviation}/{number}/{chapter}.json",
                    "sha": "0" * 40,
                }
            document["books"].append({"nr": number, "name": name, "chapters": chapters})
            index[str(number)] = {
                "translation": document["translation"],
                "abbreviation": abbreviation,
                "lang": language,
                "nr": number,
                "name": name,
                "url": f"https://api.getbible.net/v2/{abbreviation}/{number}.json",
                "sha": "0" * 40,
            }
            book_dir = root / abbreviation / str(number)
            book_dir.mkdir(parents=True, exist_ok=True)
            (book_dir / "chapters.json").write_text(
                json.dumps(chapter_index, ensure_ascii=False, indent=1), encoding="utf-8"
            )
        payload = json.dumps(document, ensure_ascii=False).encode("utf-8")
        sha = hashlib.sha1(payload, usedforsecurity=False).hexdigest()
        (root / f"{abbreviation}.json").write_bytes(payload)
        (root / f"{abbreviation}.sha").write_text(sha + "\n", encoding="ascii")
        (root / abbreviation).mkdir(exist_ok=True)
        (root / abbreviation / "books.json").write_text(
            json.dumps(index, ensure_ascii=False, indent=1), encoding="utf-8"
        )
        catalogue[abbreviation] = {
            "translation": document["translation"],
            "abbreviation": abbreviation,
            "description": document["description"],
            "lang": language,
            "language": document["language"],
            "direction": "LTR",
            "encoding": "UTF-8",
            "distribution_versification": spec["versification"],
            "url": f"https://api.getbible.net/v2/{abbreviation}.json",
            "sha": sha,
        }
    (root / "translations.json").write_text(
        json.dumps(catalogue, ensure_ascii=False, indent=1), encoding="utf-8"
    )
    return root
